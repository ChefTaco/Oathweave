/**
 * Server-generated client secrets and authorization-code replay, against the real routes and a
 * migrated SQLite database.
 */
import { createHash } from 'node:crypto'
import { beforeAll, describe, expect, it, vi } from 'vitest'
vi.mock('ioredis', async () => (await import('../test-support/fake-redis.js')).ioredisModule)
vi.mock('../queue/audit-queue.js', async () => (await import('../test-support/fake-redis.js')).auditQueueModule)

const { startRealApp } = await import('../test-support/real-app.js')
const { auditEvents } = await import('../test-support/fake-redis.js')
const harness = await startRealApp()

const json = (token: string, body: unknown, method = 'POST') => ({
  method,
  headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
  body: JSON.stringify(body),
})
const form = (values: Record<string, string>) => ({
  method: 'POST',
  headers: { 'content-type': 'application/x-www-form-urlencoded' },
  body: new URLSearchParams(values).toString(),
})
let admin: { accessToken: string }

beforeAll(async () => {
  await harness.createUser({ username: 'root', password: 'root-fixture-password', roles: [{ name: 'SUPER_ADMIN', permissions: ['iam:clients:write', 'iam:clients:read'] }] })
  admin = await harness.login('root', 'root-fixture-password')
})

describe('client secrets', () => {
  it('are generated by the server, returned once and usable', async () => {
    const created = await harness.request('/api/v1/clients', json(admin.accessToken, { name: 'generated-client', grantTypes: ['client_credentials'] }))
    expect(created.status).toBe(201)
    expect(created.headers.get('cache-control')).toBe('no-store')
    const body = (await created.json()) as { client: { id: string }; clientSecret: string }
    expect(body.clientSecret).toMatch(/^[A-Za-z0-9_-]{43}$/)
    const token = await harness.request('/api/v1/oauth/token', form({ grant_type: 'client_credentials', client_id: body.client.id, client_secret: body.clientSecret }))
    expect(token.status).toBe(200)
    // Listing never shows it again.
    const listed = await (await harness.request('/api/v1/clients', { headers: { authorization: `Bearer ${admin.accessToken}` } })).text()
    expect(listed).not.toContain(body.clientSecret)

    const rotated = await harness.request(`/api/v1/clients/${body.client.id}/rotate-secret`, { method: 'POST', headers: { authorization: `Bearer ${admin.accessToken}` } })
    expect(rotated.status).toBe(200)
    const { clientSecret } = (await rotated.json()) as { clientSecret: string }
    expect(clientSecret).not.toBe(body.clientSecret)
    expect((await harness.request('/api/v1/oauth/token', form({ grant_type: 'client_credentials', client_id: body.client.id, client_secret: body.clientSecret }))).status).toBe(401)
    expect((await harness.request('/api/v1/oauth/token', form({ grant_type: 'client_credentials', client_id: body.client.id, client_secret: clientSecret }))).status).toBe(200)
  })

  it('still accept a caller-chosen secret, which is never echoed', async () => {
    const chosen = 'caller-chosen-secret-'.padEnd(40, 'y')
    const created = await harness.request('/api/v1/clients', json(admin.accessToken, { name: 'chosen-client', secret: chosen, grantTypes: ['client_credentials'] }))
    expect(created.status).toBe(201)
    const body = await created.json()
    expect(body.clientSecret).toBeUndefined()
    expect(JSON.stringify(body)).not.toContain(chosen)
    expect((await harness.request(`/api/v1/clients/${body.client.id}/rotate-secret`, json(admin.accessToken, { secret: chosen + 'z' }))).status).toBe(200)
  })

  it('are refused for public clients', async () => {
    const response = await harness.request('/api/v1/clients', json(admin.accessToken, { name: 'public-with-secret', clientType: 'public', secret: 'x'.repeat(32), redirectUris: ['https://app.example.com/cb'] }))
    expect(response.status).toBe(400)
  })
})

describe('a replayed authorization code', () => {
  const redirectUri = 'https://app.example.com/callback'
  const verifier = 'dBjftJeZ4CVP-mB92K27uhbUJU1p1r_wW1gFWFOEjXk'
  const challenge = createHash('sha256').update(verifier).digest('base64url')

  async function code(token: string, clientId: string): Promise<string> {
    const response = await harness.request('/api/v1/oauth/authorize', json(token, {
      clientId, redirectUri, responseType: 'code', scope: 'openid', codeChallenge: challenge, codeChallengeMethod: 'S256', consent: 'approve',
    }))
    expect(response.status).toBe(200)
    return ((await response.json()) as { code: string }).code
  }
  const exchange = (clientId: string, value: string, codeVerifier = verifier) =>
    harness.request('/api/v1/oauth/token', form({ grant_type: 'authorization_code', client_id: clientId, code: value, redirect_uri: redirectUri, code_verifier: codeVerifier }))

  it('revokes the session its first exchange issued tokens for', async () => {
    await harness.createClient({ id: 'replay-spa', clientType: 'public', grantTypes: ['authorization_code', 'refresh_token'], redirectUris: [redirectUri] })
    await harness.createUser({ username: 'dana', password: 'dana-fixture-password' })
    const dana = await harness.login('dana', 'dana-fixture-password')
    const value = await code(dana.accessToken, 'replay-spa')
    const first = await exchange('replay-spa', value)
    expect(first.status).toBe(200)
    const tokens = (await first.json()) as { access_token: string; refresh_token: string }
    expect((await harness.request('/api/v1/auth/me', { headers: { authorization: `Bearer ${tokens.access_token}` } })).status).toBe(200)

    const replay = await exchange('replay-spa', value)
    expect(replay.status).toBe(400)
    expect(await replay.json()).toMatchObject({ error: 'invalid_grant' })
    expect((await harness.request('/api/v1/auth/me', { headers: { authorization: `Bearer ${tokens.access_token}` } })).status).toBe(401)
    expect((await harness.request('/api/v1/oauth/token', form({ grant_type: 'refresh_token', client_id: 'replay-spa', refresh_token: tokens.refresh_token }))).status).toBe(400)
    expect(auditEvents.find((event) => event.eventType === 'oauth.code_reuse')).toMatchObject({ detail: { sessionRevoked: true } })
    // The user's own sign-in session is a different session and stays.
    expect((await harness.request('/api/v1/auth/me', { headers: { authorization: `Bearer ${dana.accessToken}` } })).status).toBe(200)
  })

  it('without the PKCE verifier is refused and revokes nothing', async () => {
    await harness.createUser({ username: 'erin', password: 'erin-fixture-password' })
    const erin = await harness.login('erin', 'erin-fixture-password')
    const value = await code(erin.accessToken, 'replay-spa')
    const tokens = (await (await exchange('replay-spa', value)).json()) as { access_token: string }
    const forged = await exchange('replay-spa', value, 'x'.repeat(43))
    expect(forged.status).toBe(400)
    expect((await harness.request('/api/v1/auth/me', { headers: { authorization: `Bearer ${tokens.access_token}` } })).status).toBe(200)
  })
})

describe('the legacy password escrow column', () => {
  it('is gone from the migrated schema', async () => {
    const columns = (await harness.prisma.$queryRawUnsafe('PRAGMA table_info("users")')) as { name: string }[]
    expect(columns.map((column) => column.name)).not.toContain('encryptedPassword')
  })
})
