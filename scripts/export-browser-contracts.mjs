import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const entry = 'apps/iam-core/src/schemas/browser-contracts.ts';
const result = await build({ entryPoints:[entry], bundle:true, write:false, packages:'external', platform:'neutral', format:'esm', target:'es2022', legalComments:'inline' });
const code = result.outputFiles[0].text;
if (/from ["'](?!zod["'])/.test(code)) throw Error('Browser contracts must import only Zod');
const names = [...code.matchAll(/\b(\w+Schema)[,\n]/g)].map(match=>match[1]).filter((name,index,values)=>values.indexOf(name)===index).sort();
const version=JSON.parse(readFileSync('apps/iam-core/package.json')).version;
const output=`// Generated by Oathweave ${version}; Apache-2.0. Source attribution: Oathweave, extracted from Hive.\n`+code+names.map(name=>`export type ${name.slice(0,-6)} = ZodTypes.${name.includes('Request')?'input':'infer'}<typeof ${name}>;\n`).join('');
// Bundled imports use z, z2 etc; a dedicated type-only namespace keeps exports stable.
const text="import type {z as ZodTypes} from 'zod';\n"+output;
const file='docs/browser-contracts.ts';
if(process.argv.includes('--check')) { if(readFileSync(file,'utf8')!==text)throw Error('Oathweave browser export drift'); }
else writeFileSync(file,text);
console.log('Oathweave browser contracts SHA256 '+createHash('sha256').update(text).digest('hex'));
